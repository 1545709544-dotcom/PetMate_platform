/** 需要剥离的行政区划后缀，长后缀在前，避免「特别行政区」被「区」先截断。 */
const CITY_SUFFIXES = [
  '特别行政区', '维吾尔自治区', '回族自治区', '壮族自治区', '自治区',
  '自治州', '地区', '盟', '市', '县',
]

/**
 * 把地区级联值（`省/市/区`）收敛成社区「同城」用的城市短名。
 *
 * 社区 feed 的 city 过滤在后端是精确匹配，写入端与查询端口径必须一致，
 * 否则「上海市/上海市/徐汇区」永远匹配不到帖子里的「上海」。
 * 与后端 `com.petmate.common.CityUtil.normalize` 保持同一套规则。
 *
 * @example regionToCity('上海市/上海市/徐汇区') // => '上海'
 * @example regionToCity('河南省/驻马店市/驿城区') // => '驻马店'
 */
export function regionToCity(region?: string | null): string {
  if (!region) return ''
  const parts = String(region).trim().split(/[/\s]+/).filter(Boolean)
  if (!parts.length) return ''
  let city = (parts.length >= 2 ? parts[1] : parts[0]).trim()
  for (const suffix of CITY_SUFFIXES) {
    if (city.length > suffix.length && city.endsWith(suffix)) {
      city = city.slice(0, -suffix.length)
      break
    }
  }
  return city
}
