-- ---------------------------------------------------------------------------
-- E. 起价回填：t_service_item.price 统一维护为「最低档位价」，用于列表页"¥xx 起"
-- ---------------------------------------------------------------------------
UPDATE t_service_item si
   SET si.price = IFNULL((SELECT MIN(sp.price) FROM t_service_spec sp
                           WHERE sp.service_id = si.id AND sp.is_deleted = 0), si.price)
 WHERE si.is_deleted = 0;

-- 时长同步为最低档位时长
UPDATE t_service_item si
   SET si.duration = IFNULL((SELECT sp.duration FROM t_service_spec sp
                              WHERE sp.service_id = si.id AND sp.is_deleted = 0
                              ORDER BY sp.price ASC LIMIT 1), si.duration)
 WHERE si.is_deleted = 0;
